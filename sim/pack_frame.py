#!/usr/bin/env python3
"""Pack a simulator PNG into firmware/src/sim_home.h.

In the sim, pick the screen, set the waveform to Instant, and Download PNG.
The canvas is 300×400. Then:

  python3 sim/pack_frame.py path/to/frame.png
"""

import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware" / "src" / "sim_home.h"
W, H = 300, 400


def read_png(path):
    data = Path(path).read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise SystemExit("%s is not a PNG" % path)
    pos = 8
    width = height = bit = color = inter = None
    idat = b""
    while pos + 8 <= len(data):
        length, typ = struct.unpack(">I4s", data[pos:pos + 8])
        chunk = data[pos + 8:pos + 8 + length]
        pos += 12 + length
        if typ == b"IHDR":
            width, height, bit, color, _, _, inter = struct.unpack(">IIBBBBB", chunk)
        elif typ == b"IDAT":
            idat += chunk
        elif typ == b"IEND":
            break
    if inter != 0 or bit != 8 or color not in (2, 6):
        raise SystemExit("need an 8-bit RGB or RGBA PNG with no interlacing")
    if width != W or height != H:
        raise SystemExit("expected %dx%d, got %dx%d" % (W, H, width, height))
    channels = 4 if color == 6 else 3
    raw = zlib.decompress(idat)
    stride = width * channels
    rows = []
    i = 0
    prev = bytearray(stride)
    for _ in range(height):
        filt = raw[i]
        i += 1
        row = bytearray(raw[i:i + stride])
        i += stride
        for x in range(stride):
            left = row[x - channels] if x >= channels else 0
            up = prev[x]
            ul = prev[x - channels] if x >= channels else 0
            if filt == 0:
                val = row[x]
            elif filt == 1:
                val = row[x] + left
            elif filt == 2:
                val = row[x] + up
            elif filt == 3:
                val = row[x] + ((left + up) // 2)
            elif filt == 4:
                p = left + up - ul
                pa, pb, pc = abs(p - left), abs(p - up), abs(p - ul)
                pred = left if pa <= pb and pa <= pc else up if pb <= pc else ul
                val = row[x] + pred
            else:
                raise SystemExit("unknown PNG filter %s" % filt)
            row[x] = val & 0xFF
        prev = row
        rows.append(row)
    return channels, rows


def pack(channels, rows):
    stride = (W + 7) // 8
    black = bytearray(stride * H)
    red = bytearray(stride * H)
    for y, row in enumerate(rows):
        for x in range(W):
            r = row[x * channels]
            g = row[x * channels + 1]
            b = row[x * channels + 2]
            bit = 0x80 >> (x & 7)
            dest = y * stride + (x >> 3)
            if r > 140 and g < 90 and b < 90:
                red[dest] |= bit
            elif r < 80 and g < 80 and b < 80:
                black[dest] |= bit
    return stride, black, red


def c_array(name, data):
    lines = ["static const uint8_t %s[] = {" % name]
    row = []
    for i, byte in enumerate(data):
        row.append("0x%02x" % byte)
        if len(row) == 16 or i == len(data) - 1:
            lines.append("  " + ", ".join(row) + ",")
            row = []
    lines.append("};")
    return "\n".join(lines)


def main():
    if len(sys.argv) != 2:
        raise SystemExit("usage: python3 sim/pack_frame.py frame.png")
    channels, rows = read_png(sys.argv[1])
    stride, black, red = pack(channels, rows)
    text = "\n".join([
        "#pragma once",
        "",
        "// Pixel copy of a simulator frame. Regenerated by sim/pack_frame.py.",
        "// 300x400, row-major, 8 pixels per byte, high bit is the leftmost pixel.",
        "",
        "static const int SIM_W = %d;" % W,
        "static const int SIM_H = %d;" % H,
        "static const int SIM_STRIDE = %d;" % stride,
        "",
        c_array("SIM_BLACK", black),
        "",
        c_array("SIM_RED", red),
        "",
    ])
    OUT.write_text(text)
    print("wrote %s (%d black, %d red)" % (
        OUT,
        sum(bin(b).count("1") for b in black),
        sum(bin(b).count("1") for b in red),
    ))


if __name__ == "__main__":
    main()
